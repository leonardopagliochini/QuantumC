#!/usr/bin/env python3
"""
whole_benchmark.py — Parallel, end-to-end benchmarking:

Per C file it collects:
  - Cyclomatic Complexity (Lizard)
  - Instruction Count Ir (Valgrind/Callgrind) on target arch (whole program by default)
  - Circuit metrics from QASM (num_qubits, total_gates, cx, measure, u1,u2,u3, depth)
  - Toolchain timings (wall, user, sys) and memory usage (peak RSS + /proc status snapshot)
  - Optional heap profiling via Valgrind massif/dhat (separate pass)

Parallelized across files, and rows are sorted at the end by (cyclomatic, ir_instructions, file).

Output CSV defaults to tools/results/<corpus>_whole_benchmark.csv
Compiled binaries saved under tools/results/bin, QASM is generated by the pipeline under output/ by default.

Usage example:
  python tools/whole_benchmark.py --corpus corpus_c --bits 16 --arch x86-64 --progress plain
"""

