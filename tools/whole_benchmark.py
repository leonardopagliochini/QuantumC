# ---------- CC via Lizard ----------
def _run_lizard(args: List[str]) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, "-m", "lizard", *args], capture_output=True, text=True)


def cyclomatic_lizard(c_path: pathlib.Path) -> float:
    res = _run_lizard(["-l", "c", "-j", str(c_path)])
    if res.returncode == 0:
        try:
            data = json.loads(res.stdout)
            funcs = data[0].get("functions", [])
            return float(sum(f.get("cyclomatic_complexity", 1) for f in funcs)) if funcs else 1.0
        except Exception:
            pass
    res2 = _run_lizard(["-j", str(c_path)])
    if res2.returncode == 0:
        try:
            data = json.loads(res2.stdout)
            funcs = data[0].get("functions", [])
            return float(sum(f.get("cyclomatic_complexity", 1) for f in funcs)) if funcs else 1.0
        except Exception:
            pass
    try:
        text = c_path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return 1.0
    tokens = [r"\bif\b", r"\bfor\b", r"\bwhile\b", r"\bcase\b", r"&&", r"\|\|", r"\?"]
    cc = 1
    import re as _re
    for pat in tokens:
        cc += len(_re.findall(pat, text))
    return float(cc)


# ---------- Compile C for Callgrind ----------
def compile_c_for_valgrind(c_path: pathlib.Path, out_bin: pathlib.Path, cc="gcc", arch: Optional[str] = None):
    cmd = [cc, "-O0", "-g", str(c_path), "-o", str(out_bin)]
    if arch:
        arch_l = arch.lower()
        if arch_l == "arm":
            cmd.insert(1, "-march=armv7-a")
        elif arch_l in ("x86", "i686"):
            cmd.insert(1, "-march=i686")
        elif arch_l in ("x86-64", "x86_64", "amd64"):
            cmd.insert(1, "-march=x86-64")
    # Capture outputs so we can print the full error on failure
    proc = subprocess.run(cmd, check=False, capture_output=True, text=True)
    if proc.returncode != 0:
        raise subprocess.CalledProcessError(proc.returncode, cmd, output=proc.stdout, stderr=proc.stderr)


# ---------- Ir via Callgrind ----------
def callgrind_ir(bin_path: pathlib.Path, run_cmd: Optional[str] = None, roi_func: Optional[str] = None) -> Optional[int]:
    if shutil.which("valgrind") is None:
        return None
    has_annot = shutil.which("callgrind_annotate") is not None
    try:
        bin_path.chmod(bin_path.stat().st_mode | 0o111)
    except Exception:
        pass
    with tempfile.TemporaryDirectory() as td:
        tmp_bin = pathlib.Path(td) / bin_path.name
        shutil.copy2(bin_path, tmp_bin)
        tmp_bin.chmod(tmp_bin.stat().st_mode | 0o111)
        cg_out = pathlib.Path(td) / "callgrind.out"
        env = os.environ.copy()
        env["LANG"] = "C"
        env["LC_ALL"] = "C"
        vg_cmd = [
            "valgrind",
            "--tool=callgrind",
            f"--callgrind-out-file={str(cg_out)}",
            str(tmp_bin)
        ]
        if roi_func:
            vg_cmd.insert(2, f"--toggle-collect={roi_func}")
            vg_cmd.insert(2, "--collect-atstart=no")
        res = subprocess.run(vg_cmd, input=run_cmd if run_cmd else None, text=True, capture_output=True, env=env)
        if not cg_out.exists():
            return None
        if has_annot:
            ann = subprocess.run(["callgrind_annotate", str(cg_out)], capture_output=True, text=True, env=env)
            if ann.returncode == 0:
                m = re.search(r"\bIr\s*:\s*([\d,\.]+)", ann.stdout)
                if m:
                    return int(m.group(1).replace(",", "").replace(".", ""))
        try:
            raw = cg_out.read_text()
            ev_m = re.search(r"^events:\s*(.+)$", raw, re.MULTILINE)
            if not ev_m:
                return None
            events = ev_m.group(1).strip().split()
            try:
                ir_idx = events.index("Ir")
            except ValueError:
                return None
            sum_m = re.search(r"^summary:\s*([^\n]+)$", raw, re.MULTILINE)
            if not sum_m:
                return None
            nums = re.split(r"\s+", sum_m.group(1).strip())
            def clean_num(s: str) -> str:
                return re.sub(r"[,_\.]", "", s)
            if ir_idx < len(nums):
                return int(clean_num(nums[ir_idx]))
            elif len(nums) == 1 and ir_idx == 0:
                return int(clean_num(nums[0]))
            return None
        except Exception:
            return None


# ---------- QASM metrics ----------
_QREG_RE     = re.compile(r"qreg\s+\w+\[(\d+)\];")
_CX_RE       = re.compile(r"^\s*cx\s", re.MULTILINE)
_MEASURE_RE  = re.compile(r"^\s*measure\s", re.MULTILINE)
_U1_RE       = re.compile(r"^\s*u1\(", re.MULTILINE)
_U2_RE       = re.compile(r"^\s*u2\(", re.MULTILINE)
_U3_RE       = re.compile(r"^\s*u3\(", re.MULTILINE)
_QBIT_TOK_RE = re.compile(r"([A-Za-z_]\w*)\s*\[\s*(\d+)\s*\]")


def _is_comment_or_header(s: str) -> bool:
    return ((not s) or s.startswith("//") or s.startswith("OPENQASM") or s.startswith("include") or s.startswith("qreg") or s.startswith("creg"))


def compute_qasm_depth(qasm_text: str) -> int:
    last_layer: Dict[str, int] = {}
    depth = 0
    for raw in qasm_text.splitlines():
        s = raw.strip()
        if _is_comment_or_header(s):
            continue
        if s.startswith("barrier"):
            qubits = [f"{n}[{i}]" for n, i in _QBIT_TOK_RE.findall(s)]
            if not qubits:
                if last_layer:
                    bump = max(last_layer.values()) + 1
                    for q in list(last_layer.keys()):
                        last_layer[q] = bump
                    depth = max(depth, bump)
            else:
                cur_max = 0
                for q in qubits:
                    cur_max = max(cur_max, last_layer.get(q, 0))
                new_layer = cur_max + 1
                for q in qubits:
                    last_layer[q] = new_layer
                depth = max(depth, new_layer)
            continue
        if s.startswith("measure"):
            mqs = _QBIT_TOK_RE.findall(s)
            if not mqs:
                continue
            qubits = [f"{n}[{i}]" for n, i in mqs]
            layer = 1 + max((last_layer.get(q, 0) for q in qubits), default=0)
            for q in qubits:
                last_layer[q] = layer
            depth = max(depth, layer)
            continue
        mqs = _QBIT_TOK_RE.findall(s)
        if not mqs:
            continue
        qubits = [f"{n}[{i}]" for n, i in mqs]
        layer = 1 + max((last_layer.get(q, 0) for q in qubits), default=0)
        for q in qubits:
            last_layer[q] = layer
        depth = max(depth, layer)
    return depth


def count_qasm_metrics(qasm_path: pathlib.Path) -> Dict[str, Optional[int]]:
    text = qasm_path.read_text()
    qubits = sum(int(m.group(1)) for m in _QREG_RE.finditer(text))
    num_cx = len(_CX_RE.findall(text))
    num_measure = len(_MEASURE_RE.findall(text))
    num_u1 = len(_U1_RE.findall(text))
    num_u2 = len(_U2_RE.findall(text))
    num_u3 = len(_U3_RE.findall(text))
    depth = compute_qasm_depth(text)
    # total_gates as rough sum
    total_gates = num_cx + num_measure + num_u1 + num_u2 + num_u3
    return dict(num_qubits=qubits, total_gates=total_gates, num_cx=num_cx, num_measure=num_measure, num_u1=num_u1, num_u2=num_u2, num_u3=num_u3, depth=depth)


# ---------- Toolchain subprocess (timing + memory) ----------
def run_toolchain_subprocess(c_path: pathlib.Path, bits: int, max_iter: int) -> Tuple[Optional[str], Dict[str, Optional[Union[int, float, str]]]]:
    """
    Runs pipeline.compile_c_file in a child Python process under /usr/bin/time -v.
    Returns (qasm_path, metrics_dict) where metrics include wall/user/sys times, max RSS, and /proc status fields from the child process.
    """
    code = f"""
import json, os
from pipeline import compile_c_file
q = compile_c_file({json.dumps(str(c_path))}, run=False, max_iter={int(max_iter)})
status = {{}}
try:
    with open(f"/proc/{{os.getpid()}}/status") as f:
        for line in f:
            if line.startswith(("VmSize:", "VmData:", "VmStk:", "VmExe:", "VmLib:", "VmRSS:", "VmHWM:")):
                k, v = line.split(":", 1)
                status[k.strip()] = v.strip()
except Exception:
    pass
print(json.dumps({{"qasm": q, "proc_status": status}}))
"""
    # /usr/bin/time -v writes to stderr; JSON is printed to stdout
    cmd = ["/usr/bin/time", "-v", sys.executable, "-c", code]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, cwd=str(ROOT))
    except FileNotFoundError:
        # Fallback without external time - no RSS, only JSON stdout
        proc = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, cwd=str(ROOT))
    qasm_path = None
    meta: Dict[str, Optional[Union[int, float, str]]] = {
        "wall_time_s": None,
        "user_time_s": None,
        "sys_time_s": None,
        "max_rss_kb": None,
        "VmSize_kB": None,
        "VmData_kB": None,
        "VmStk_kB": None,
        "VmExe_kB": None,
        "VmLib_kB": None,
        "VmRSS_kB": None,
        "VmHWM_kB": None,
    }
    # always record return code and raw outputs for diagnostics
    meta["returncode"] = proc.returncode
    meta["stderr"] = proc.stderr
    meta["stdout"] = proc.stdout

    # parse JSON stdout
    try:
        js = json.loads(proc.stdout.strip().splitlines()[-1]) if proc.stdout.strip() else {}
        qasm_path = js.get("qasm")
        st = js.get("proc_status", {})
        def pick(k):
            v = st.get(k)
            if not v:
                return None
            m = re.search(r"(\d+)", v)
            return int(m.group(1)) if m else None
        meta["VmSize_kB"] = pick("VmSize")
        meta["VmData_kB"] = pick("VmData")
        meta["VmStk_kB"] = pick("VmStk")
        meta["VmExe_kB"] = pick("VmExe")
        meta["VmLib_kB"] = pick("VmLib")
        meta["VmRSS_kB"] = pick("VmRSS")
        meta["VmHWM_kB"] = pick("VmHWM")
    except Exception:
        pass
    # parse time -v stderr if available
    try:
        for line in proc.stderr.splitlines():
            if ":" not in line:
                continue
            key, val = line.split(":", 1)
            key = key.strip()
            val = val.strip()
            if key.startswith("User time (seconds)"):
                meta["user_time_s"] = float(val)
            elif key.startswith("System time (seconds)"):
                meta["sys_time_s"] = float(val)
            elif key.startswith("Elapsed (wall clock) time"):
                # format mm:ss or h:mm:ss
                parts = val.split(":")
                sec = 0.0
                if len(parts) == 2:
                    m, s = parts
                    sec = float(m) * 60 + float(s)
                elif len(parts) == 3:
                    h, m, s = parts
                    sec = float(h) * 3600 + float(m) * 60 + float(s)
                meta["wall_time_s"] = sec
            elif key.startswith("Maximum resident set size"):
                # reported in Kilobytes
                try:
                    meta["max_rss_kb"] = int(val)
                except Exception:
                    pass
    except Exception:
        pass
    return qasm_path, meta


# ---------- Per-file worker ----------
def process_file(
    c_path: pathlib.Path,
    *,
    bits: int,
    cc: str,
    arch: Optional[str],
    max_iter: int,
    ir_roi_func: Optional[str],
) -> Dict[str, Union[str, int, float, None]]:
    # per-file diagnostics
    status = "ok"
    errors: List[str] = []
    warnings: List[str] = []

    # CC first
    cc_val = None
    try:
        cc_val = cyclomatic_lizard(c_path)
    except Exception as e:
        warnings.append(f"cc_failed: {type(e).__name__}")

    # Build binary for Callgrind
    ir_val = None
    binp = BIN_DIR / c_path.stem
    compile_stderr = None
    try:
        compile_c_for_valgrind(c_path, binp, cc=cc, arch=arch)
        ir_val = callgrind_ir(binp, run_cmd=None, roi_func=ir_roi_func)
        if ir_val is None:
            # valgrind missing or callgrind output not produced
            warnings.append("ir_missing")
    except subprocess.CalledProcessError as e:
        errors.append(f"compile_failed: rc={e.returncode}")
        compile_stderr = e.stderr or ""
    except Exception as e:
        errors.append(f"ir_failed: {type(e).__name__}")

    # Toolchain timing + QASM
    qasm_path = None
    wall_time_s = None
    user_time_s = None
    sys_time_s = None
    max_rss_kb = None
    VmSize_kB = VmData_kB = VmStk_kB = VmExe_kB = VmLib_kB = VmRSS_kB = VmHWM_kB = None
    pipeline_stderr = None
    try:
        qasm_path, meta = run_toolchain_subprocess(c_path, bits=bits, max_iter=max_iter)
        wall_time_s = meta.get("wall_time_s")
        user_time_s = meta.get("user_time_s")
        sys_time_s  = meta.get("sys_time_s")
        max_rss_kb  = meta.get("max_rss_kb")
        VmSize_kB   = meta.get("VmSize_kB")
        VmData_kB   = meta.get("VmData_kB")
        VmStk_kB    = meta.get("VmStk_kB")
        VmExe_kB    = meta.get("VmExe_kB")
        VmLib_kB    = meta.get("VmLib_kB")
        VmRSS_kB    = meta.get("VmRSS_kB")
        VmHWM_kB    = meta.get("VmHWM_kB")
        rc = meta.get("returncode")
        pipeline_stderr = (meta.get("stderr") or None)
        if isinstance(rc, int) and rc != 0:
            # include last line of stderr for readability
            serr = (pipeline_stderr or "").splitlines()[-1:] or []
            errors.append("pipeline_failed" + (f": {serr[0]}" if serr else ""))
    except Exception as e:
        errors.append(f"pipeline_exc: {type(e).__name__}")

    # Circuit metrics from QASM
    qasm_metrics: Dict[str, Optional[int]] = {"num_qubits": None, "total_gates": None, "num_cx": None, "num_measure": None, "num_u1": None, "num_u2": None, "num_u3": None, "depth": None}
    try:
        if qasm_path:
            qasm_p = pathlib.Path(qasm_path)
            if qasm_p.exists():
                qasm_metrics = count_qasm_metrics(qasm_p)
            else:
                errors.append("qasm_missing")
        else:
            errors.append("qasm_path_none")
    except Exception as e:
        errors.append(f"qasm_metrics_failed: {type(e).__name__}")

    # derive final status
    if errors:
        status = "error"
    elif (cc_val is None) or (ir_val is None):
        status = "partial"
    else:
        status = "ok"

    return {
        "status": status,
        "error": "; ".join(errors) if errors else None,
        "warnings": "; ".join(warnings) if warnings else None,
        "compile_stderr": compile_stderr,
        "pipeline_stderr": pipeline_stderr,
        "cyclomatic": cc_val,
        "ir_instructions": ir_val,
        "num_qubits": qasm_metrics.get("num_qubits"),
        "total_gates": qasm_metrics.get("total_gates"),
        "num_cx": qasm_metrics.get("num_cx"),
        "num_measure": qasm_metrics.get("num_measure"),
        "num_u1": qasm_metrics.get("num_u1"),
        "num_u2": qasm_metrics.get("num_u2"),
        "num_u3": qasm_metrics.get("num_u3"),
        "depth": qasm_metrics.get("depth"),
        "wall_time_s": wall_time_s,
        "user_time_s": user_time_s,
        "sys_time_s": sys_time_s,
        "max_rss_kb": max_rss_kb,
        "VmSize_kB": VmSize_kB,
        "VmData_kB": VmData_kB,
        "VmStk_kB": VmStk_kB,
        "VmExe_kB": VmExe_kB,
        "VmLib_kB": VmLib_kB,
        "VmRSS_kB": VmRSS_kB,
        "VmHWM_kB": VmHWM_kB,
        "bin_path": str(binp),
        "qasm_path": qasm_path,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", type=str, required=True, help="Folder with .c files")
    ap.add_argument("--out", type=str, default=None, help="Output CSV (default: tools/results/<corpus>_whole_benchmark.csv)")
    ap.add_argument("--cc", type=str, default="gcc", help="C compiler for binary (default: gcc)")
    ap.add_argument("--arch", type=str, default=None, help="Target arch hint (e.g., x86-64, arm)")
    ap.add_argument("--bits", type=int, default=16, help="Bit width for pipeline (default: 16)")
    ap.add_argument("--max-iter", type=int, default=30, help="Max unroll for pipeline lowering (default: 30)")
    ap.add_argument("--progress", choices=["auto", "plain", "none"], default="auto")
    ap.add_argument("--show-stages", action="store_true")
    ap.add_argument("--ir-roi-func", type=str, default=None, help="If set, use Callgrind --toggle-collect=<func>")
    ap.add_argument("--max-workers", type=int, default=None, help="Parallel workers (default: cpu_count-1)")
    args = ap.parse_args()

    corpus = pathlib.Path(args.corpus)
    c_files = sorted(p for p in corpus.glob("*.c"))

    # Output path
    if args.out is None:
        out_csv = RESULTS_DIR / f"{corpus.name}_whole_benchmark.csv"
    else:
        out_csv = pathlib.Path(args.out)

    # Progress
    def _make_progress(total: int, mode: str, desc: str = ""):
        if mode == "none":
            return None
        class _P:
            def __init__(self, total: int, desc: str):
                self.total = total; self.desc = desc; self.count = 0
                self._start = time.perf_counter(); self._last = 0
                self._print()
            def _print(self):
                pct = (self.count / self.total * 100.0) if self.total else 0.0
                el = time.perf_counter() - self._start
                sys.stdout.write("\r" + " " * self._last + "\r")
                s = f"{self.desc}: {self.count}/{self.total} ({pct:5.1f}%) | {el:6.1f}s"
                sys.stdout.write(s); sys.stdout.flush(); self._last = len(s)
            def update(self, n: int = 1):
                self.count = min(self.total, self.count + n); self._print()
            def write(self, s: str):
                sys.stdout.write("\r" + " " * self._last + "\r"); print(s); self._print()
            def close(self): self._print(); sys.stdout.write("\n"); sys.stdout.flush()
        if mode == "plain":
            return _P(total, desc)
        if mode == "auto":
            try:
                from tqdm import tqdm  # type: ignore
                class _T:
                    def __init__(self, total, desc): self._t=tqdm(total=total, desc=desc, unit="file")
                    def update(self,n=1): self._t.update(n)
                    def write(self,s:str):
                        from tqdm import tqdm as _tq; _tq.write(s.rstrip())
                    def close(self): self._t.close()
                return _T(total, desc)
            except Exception:
                return _P(total, desc)
        return _P(total, desc)

    progress = _make_progress(len(c_files), args.progress, "Files")

    # Parallel map
    results: List[Dict[str, Union[str, int, float, None]]] = []
    max_workers = args.max_workers or max(1, (os.cpu_count() or 2) - 1)
    try:
        with concurrent.futures.ThreadPoolExecutor(max_workers=max_workers) as ex:
            futs = {
                ex.submit(
                    process_file,
                    c_path,
                    bits=args.bits,
                    cc=args.cc,
                    arch=args.arch,
                    max_iter=args.max_iter,
                    ir_roi_func=args.ir_roi_func,
                ): c_path for c_path in c_files
            }
            for fut in concurrent.futures.as_completed(futs):
                c_path = futs[fut]
                try:
                    r = fut.result()
                except Exception as e:
                    # Ensure failures are recorded into CSV as error rows
                    r = {"status": "error", "error": f"worker_exc: {type(e).__name__}", "file": c_path.name}
                    print(traceback.format_exc(), file=sys.stderr)
                else:
                    r["file"] = c_path.name
                finally:
                    results.append(r)
                    # stage log reflecting status
                    if args.show_stages and progress:
                        st = r.get("status") or "?"
                        em = r.get("error") or ""
                        if st == "ok":
                            progress.write(f"{c_path.name}: OK")
                        elif st == "partial":
                            progress.write(f"{c_path.name}: PARTIAL {em}")
                        else:
                            progress.write(f"{c_path.name}: ERROR {em}")
                            # Print full error output when available
                            comp_err = (r.get("compile_stderr") or "").strip()
                            pipe_err = (r.get("pipeline_stderr") or "").strip()
                            if comp_err:
                                progress.write(f"--- {c_path.name}: compiler stderr ---")
                                for ln in comp_err.splitlines():
                                    progress.write(ln)
                            if pipe_err:
                                progress.write(f"--- {c_path.name}: pipeline stderr ---")
                                for ln in pipe_err.splitlines():
                                    progress.write(ln)
                    if progress: progress.update(1)
    finally:
        if progress: progress.close()

    # Sort rows
    def _to_float(v):
        try: return float(v)
        except Exception: return float("inf")
    def _to_int(v):
        try: return int(v)
        except Exception:
            try: return int(float(v))
            except Exception: return 10**18
    results.sort(key=lambda r: (_to_float(r.get("cyclomatic")), _to_int(r.get("ir_instructions")), r.get("file") or ""))

    # Write CSV
    out_csv.parent.mkdir(parents=True, exist_ok=True)
    fields = [
        "file","status","error","warnings","cyclomatic","ir_instructions",
        "num_qubits","total_gates","num_cx","num_measure","num_u1","num_u2","num_u3","depth",
        "wall_time_s","user_time_s","sys_time_s","max_rss_kb",
        "VmSize_kB","VmData_kB","VmStk_kB","VmExe_kB","VmLib_kB","VmRSS_kB","VmHWM_kB",
        "bin_path","qasm_path",
        "compile_stderr","pipeline_stderr",
    ]
    with out_csv.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(results)
    # summary
    total = len(c_files)
    ok_n = sum(1 for r in results if r.get("status") == "ok")
    partial_n = sum(1 for r in results if r.get("status") == "partial")
    err_n = sum(1 for r in results if r.get("status") == "error")
    print(f"[RESULTS] Written: {out_csv}")
    print(f"[SUMMARY] Files: {total} — ok={ok_n}, partial={partial_n}, error={err_n}")
    if err_n:
        print("[ERRORS] First failures:")
        for r in (x for x in results if x.get("status") == "error"):
            print(f"  - {r.get('file')}: {r.get('error')}")
            err_n -= 1
            if err_n <= 0:
                break


